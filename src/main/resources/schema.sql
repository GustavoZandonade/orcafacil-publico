CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL CHECK (CHAR_LENGTH(TRIM(name)) > 0),
    email VARCHAR(180) NOT NULL DEFAULT '',
    cnpj VARCHAR(18) NOT NULL DEFAULT '',
    address VARCHAR(300) NOT NULL DEFAULT '',
    responsible_name VARCHAR(120) NOT NULL DEFAULT ''
);
ALTER TABLE customers ADD COLUMN IF NOT EXISTS cnpj VARCHAR(18) NOT NULL DEFAULT '';
ALTER TABLE customers ADD COLUMN IF NOT EXISTS address VARCHAR(300) NOT NULL DEFAULT '';
ALTER TABLE customers ADD COLUMN IF NOT EXISTS responsible_name VARCHAR(120) NOT NULL DEFAULT '';
CREATE TABLE IF NOT EXISTS quotes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    title VARCHAR(140) NOT NULL CHECK (CHAR_LENGTH(TRIM(title)) > 0),
    description VARCHAR(2000) NOT NULL DEFAULT '',
    valid_until DATE NOT NULL,
    discount DECIMAL(16,2) NOT NULL DEFAULT 0 CHECK (discount >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'RASCUNHO'
      CHECK (status IN ('RASCUNHO','ENVIADO','APROVADO','REJEITADO','CANCELADO')),
    version INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS quote_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id BIGINT NOT NULL REFERENCES quotes(id) ON DELETE CASCADE,
    description VARCHAR(200) NOT NULL CHECK (CHAR_LENGTH(TRIM(description)) > 0),
    quantity DECIMAL(9,3) NOT NULL CHECK (quantity > 0 AND quantity <= 10000),
    unit_price DECIMAL(12,2) NOT NULL CHECK (unit_price >= 0 AND unit_price <= 1000000),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
      CHECK (status IN ('PENDENTE','EM_PRODUCAO','CONCLUIDO')),
    image_data CLOB
);
ALTER TABLE quotes ADD COLUMN IF NOT EXISTS description VARCHAR(2000) NOT NULL DEFAULT '';
ALTER TABLE quote_items ADD COLUMN IF NOT EXISTS status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE';
ALTER TABLE quote_items ADD COLUMN IF NOT EXISTS image_data CLOB;
CREATE INDEX IF NOT EXISTS idx_quotes_customer ON quotes(customer_id);
CREATE INDEX IF NOT EXISTS idx_items_quote ON quote_items(quote_id);
